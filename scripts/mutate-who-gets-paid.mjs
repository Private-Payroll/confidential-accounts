/**
 * The last twenty lines of whatever the child said, for a report a person
 * reads. Empty in, empty out — a missing reason is printed as a missing reason
 * and never as a blank space that reads like nothing happened.
 */
const tail = (text, n = 20) => {
  const ls = String(text ?? '').split('\n').map(l => l.trimEnd()).filter(l => l !== '');
  return ls.length ? ls.slice(-n) : ['(the child printed nothing)'];
};

/**
 * Runs the suite and returns what it actually COLLECTED — not merely what it
 * PARSED.
 *
 * **`ran` MEANT *THE JSON PARSED*, AND THAT WAS THIS FILE'S DEFECT.** the collected-nothing scoring defect,
 * the collected-nothing scoring defect, fixed in `scripts/mutate-authority.mjs` and
 * `scripts/mutate-payslip-key.mjs` by the earlier fix to two harnesses and copied here because it is the
 * same `runSuite`, sixteen times over.
 *
 * A vitest run that collects NOTHING — a `globalSetup` that threw, a config
 * error, a crashed worker, a suite file that failed to COLLECT — still writes a
 * well-formed report: `numTotalTests: 0`, `testResults: []`, `success: false`,
 * exit 1. **That parses.** `failures` is then `0`, and this file printed
 * *SURVIVED. The code was broken and every test still passed* — the loudest
 * sentence it owns, about a run in which not one assertion executed. **A door a
 * person is trained to ignore has stopped being a door.**
 *
 * **AND THE OTHER HALF NEVER REACHED `ran` AT ALL.** `flatMap(r =>
 * r.assertionResults ?? [])` swallows a suite entry that collected nothing — a
 * broken import, a module-scope throw. Such a report names its file, parses,
 * and yields an empty assertion list. `emptyFiles` is that case named. **This
 * harness has ONE suite file, which makes that route the more likely of the
 * two, not the less: a mutation to `src/core/payroll.ts` that breaks the module is a
 * mutation whose only test file cannot import.**
 *
 * So: `ran` means ASSERTIONS WERE COLLECTED; `collected` is the number to
 * compare against the baseline's; `byFile` keeps each assertion's suite file;
 * and **`stderr` IS KEPT**, because on a suite that refused to START it is the
 * only place the reason exists at all.
 */
function runSuite(tag) {
  const file = join(OUT, `${tag}.json`);
  /* Removed first, so a run that writes nothing cannot be scored against the
   * PREVIOUS run's report sitting at the same path. */
  try { rmSync(file); } catch { /* first run */ }
  let said = '';
  try {
    execFileSync('./node_modules/.bin/vitest',
      ['run', ...SUITES, '--reporter=json', `--outputFile=${file}`],
      { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (e) {
    /* A failing suite exits non-zero, which is the ordinary case here, so this
     * is not an error path. What it does is KEEP the child's own words. */
    said = [e?.stderr, e?.stdout].map(b => (b ? String(b) : '')).join('\n');
  }
  let json;
  try { json = JSON.parse(readFileSync(file, 'utf8')); }
  catch {
    return {
      ran: false, collected: 0, emptyFiles: [], byFile: [], titles: [],
      failed: [], passed: 0, failures: 0, said,
      why: 'vitest wrote no report this run could parse',
    };
  }
  const suites = json.testResults ?? [];
  const byFile = suites.flatMap(r => (r.assertionResults ?? []).map(a => ({
    file: r.name ?? '(unnamed suite)', title: a.title, status: a.status,
  })));
  const emptyFiles = suites
    .filter(r => (r.assertionResults ?? []).length === 0)
    .map(r => r.name ?? '(unnamed suite)');
  return {
    ran: byFile.length > 0,
    why: byFile.length > 0 ? ''
      : `vitest wrote a report naming ${suites.length} suite file(s) and NOT ONE assertion`,
    collected: byFile.length,
    emptyFiles,
    byFile,
    said,
    /* **A SKIPPED ASSERTION IS NOT ONE THAT RAN.** When a `beforeAll` throws,
     * vitest returns the file's assertions with `status: 'skipped'` and reports
     * ZERO failures — so a named guard that never executed would be present in
     * `titles`, pass the check below, and score SURVIVED. */
    titles: byFile.filter(a => a.status !== 'skipped').map(a => a.title),
    failed: byFile.filter(a => a.status === 'failed').map(a => a.title),
    passed: byFile.filter(a => a.status === 'passed').length,
    failures: byFile.filter(a => a.status === 'failed').length,
  };
}

/*
 * **A KILLED RUN PUTS THE FILE BACK, AND IT DOES NOT RELY ON A SIGNAL.** The
 * argument is `scripts/mutate-self-payee.mjs`'s in full: `execFileSync` BLOCKS
 * THE EVENT LOOP, so a `SIGTERM` arriving mid-suite cannot be serviced until the
 * call it would have interrupted has finished, and a `SIGKILL` never reaches
 * JavaScript at all. The record of what is in flight therefore lives ON DISK.
 *
 * **AND THE FILE IT GUARDS IS THE MONEY PATH**, so a leftover here is not an
 * inconvenience: it is `createRunFromRoster` sitting broken in a tree somebody
 * else is about to commit.
 */
const JOURNAL = join(OUT, 'in-flight.json');
const beginMutation = (path, before) => {
  mkdirSync(OUT, { recursive: true });
  writeFileSync(JOURNAL, JSON.stringify({ path, before }));
};
/* CLEARED, NOT DELETED: `rm` is refused on a mounted folder, and a swallowed
 * failure there left the journal behind after a good run and made the next one
 * announce a recovery that had not happened. */
const endMutation = (path, before) => {
  writeFileSync(path, before);
  writeFileSync(JOURNAL, '{}');
};
function recoverFromLastRun(say) {
  let held;
  try { held = JSON.parse(readFileSync(JOURNAL, 'utf8')); } catch { return; }
  if (!held?.path || typeof held.before !== 'string') return;
  writeFileSync(held.path, held.before);
  writeFileSync(JOURNAL, '{}');
  say('  A PREVIOUS RUN WAS KILLED WITH A MUTATION STILL IN THE TREE.');
  say(`  ${held.path} has been put back before anything else was done.`);
  say('');
}

